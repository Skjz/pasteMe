import AppKit

/// 在 `NSPasteboard` 与 `ClipContent` 之间转换。
public enum PasteboardCodec {
    /// PasteMe 自己写回剪贴板时附带的标记，监听器据此跳过这次变化。
    public static let ownMarker = NSPasteboard.PasteboardType("io.github.skjz.PasteMe.own")

    /// 约定俗成的标记（见 nspasteboard.org）：密码管理器等应用用它们声明内容不应被记录。
    static let ignoredMarkers: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    public static func isOwnWrite(_ pasteboard: NSPasteboard) -> Bool {
        pasteboard.types?.contains(ownMarker) ?? false
    }

    public static func shouldIgnore(_ pasteboard: NSPasteboard) -> Bool {
        let types = Set(pasteboard.types ?? [])
        return ignoredMarkers.contains(where: types.contains)
    }

    /// 读取剪贴板当前内容。优先级：文件 > 文本（含链接）> 图片。
    /// 例外：同时有图片和一条链接时（如浏览器里“拷贝图片”）按图片处理。
    public static func read(_ pasteboard: NSPasteboard) -> ClipContent? {
        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            return ClipContent(kind: .file, text: urls.map(\.path).joined(separator: "\n"))
        }

        let string = pasteboard.string(forType: .string)
        let image = readImage(pasteboard)

        if let string, !string.isEmpty {
            let isLink = isWebLink(string)
            if isLink, let image {
                return ClipContent(kind: .image, image: image)
            }
            if isLink {
                return ClipContent(kind: .link, text: string.trimmingCharacters(in: .whitespacesAndNewlines))
            }
            return ClipContent(kind: .text, text: string, rtf: pasteboard.data(forType: .rtf))
        }

        if let image {
            return ClipContent(kind: .image, image: image)
        }
        return nil
    }

    /// 把内容写回剪贴板，并打上 `ownMarker`。`file` 是图片另存成的 PNG 文件，有的话一起写进去。
    public static func write(_ content: ClipContent, attachingFile file: URL? = nil, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        pasteboard.writeObjects(writers(for: content, attachingFile: file))
        pasteboard.setData(Data(), forType: ownMarker)
    }

    /// 写进剪贴板或拖拽的内容。文件是每个文件一项；其他类型是一项，带上它的几种写法，接收方自己挑。
    ///
    /// 图片给了 `file` 时，同一项里既有图片数据也有文件地址：访达、网页上传框这类只收文件的地方用文件，
    /// 其他应用照常用图片数据。
    public static func writers(for content: ClipContent, attachingFile file: URL? = nil) -> [NSPasteboardWriting] {
        if content.kind == .file {
            return content.fileURLs as [NSURL]
        }
        let item = NSPasteboardItem()
        switch content.kind {
        case .text:
            if let rtf = content.rtf { item.setData(rtf, forType: .rtf) }
            if let text = content.text { item.setString(text, forType: .string) }
        case .link:
            if let text = content.text {
                item.setString(text, forType: .string)
                item.setString(text, forType: .URL)
            }
        case .image:
            if let png = content.image {
                item.setData(png, forType: .png)
                // 有些应用只认 TIFF。
                if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                    item.setData(tiff, forType: .tiff)
                }
            }
            if let file {
                item.setString(file.absoluteString, forType: .fileURL)
            }
        case .file:
            break
        }
        return [item]
    }

    static func readImage(_ pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        if let tiff = pasteboard.data(forType: .tiff) {
            return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
        }
        return nil
    }

    /// 整段内容是否就是一个 http(s) 链接。
    public static func isWebLink(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(),
              scheme == "http" || scheme == "https",
              url.host != nil
        else { return false }
        return true
    }
}
